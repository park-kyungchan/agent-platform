import { createHash } from "node:crypto";
import { cp, lstat, mkdtemp, readFile, readdir, realpath, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative, sep } from "node:path";
import { runNativeCommand } from "./native-tools";

export async function generatedTree(directory: string): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const visit = async (path: string): Promise<void> => {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const absolute = join(path, entry.name);
      if (entry.isSymbolicLink()) throw Error("Generated output must not contain a symlink.");
      if (entry.isDirectory()) await visit(absolute);
      else {
        const info = await lstat(absolute);
        if (!info.isFile() || info.size > 2_000_000 || (await realpath(absolute)) !== absolute)
          throw Error("Generated output must be an exact bounded regular file.");
        files.set(
          relative(directory, absolute).split(sep).join("/"),
          createHash("sha256")
            .update(await readFile(absolute))
            .digest("hex"),
        );
      }
      if (files.size > 4096) throw Error("Generated output exceeds the bounded file budget.");
    }
  };
  try {
    const info = await lstat(directory);
    if (!info.isDirectory() || info.isSymbolicLink() || (await realpath(directory)) !== directory)
      throw Error("Generated output root must be an exact regular directory.");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return files;
    throw error;
  }
  await visit(directory);
  return files;
}

export function compareGeneratedTrees(
  reviewed: ReadonlyMap<string, string>,
  built: ReadonlyMap<string, string>,
): { status: "pass" | "fail"; changed: string[]; missing: string[]; extra: string[] } {
  const changed = [...reviewed.keys()]
    .filter((path) => built.has(path) && reviewed.get(path) !== built.get(path))
    .sort();
  const missing = [...built.keys()].filter((path) => !reviewed.has(path)).sort();
  const extra = [...reviewed.keys()].filter((path) => !built.has(path)).sort();
  return {
    status:
      reviewed.size && built.size && !changed.length && !missing.length && !extra.length
        ? "pass"
        : "fail",
    changed,
    missing,
    extra,
  };
}

/** Build a disposable package copy; reviewed generated bytes are never repaired by validation. */
export async function verifyOntologyBuild(root: string) {
  const packageRoot = join(root, "packages/ontology");
  const scratch = await mkdtemp(join(process.env.RUNNER_TEMP ?? tmpdir(), "ontology-build-"));
  try {
    const isolated = join(scratch, "ontology");
    await cp(packageRoot, isolated, {
      recursive: true,
      dereference: false,
      filter: (path) =>
        !relative(packageRoot, path)
          .split(sep)
          .some((part) => ["node_modules", "dist", ".git"].includes(part)),
    });
    // Dependencies retain native Bun resolution; no maintained package source is linked or changed.
    for (const [source, target] of [
      [join(root, "node_modules"), join(scratch, "node_modules")],
      [join(packageRoot, "node_modules"), join(isolated, "node_modules")],
    ]) {
      try {
        await symlink(await realpath(source!), target!, "dir");
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
    }
    const reviewed = await generatedTree(join(packageRoot, "dist"));
    const command = await runNativeCommand(
      "isolated-ontology-build",
      [process.execPath, "run", "build"],
      isolated,
    );
    const generated = compareGeneratedTrees(reviewed, await generatedTree(join(isolated, "dist")));
    const originalGeneratedBytesPreserved =
      compareGeneratedTrees(reviewed, await generatedTree(join(packageRoot, "dist"))).status ===
      "pass";
    return {
      status:
        command.exitCode === 0 &&
        !command.timedOut &&
        generated.status === "pass" &&
        originalGeneratedBytesPreserved
          ? ("pass" as const)
          : ("fail" as const),
      command,
      generated,
      reviewedFiles: reviewed.size,
      originalGeneratedBytesPreserved,
    };
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}
