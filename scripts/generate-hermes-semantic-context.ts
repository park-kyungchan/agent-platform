import { createHash } from "node:crypto";
import { readFile, realpath, lstat } from "node:fs/promises";
import { resolve, join } from "node:path";

/** Emits a source-pinned projection only. Native writers own publication. */
export async function generateHermesSemanticProjection(
  platformRoot = resolve(import.meta.dir, ".."),
) {
  if ((await realpath(platformRoot)) !== platformRoot)
    throw Error("Canonical platform source root required");
  const relativeSource = "packages/native-hermes-adapter/src/adoption/semantic-context.ts";
  const path = join(platformRoot, relativeSource);
  if ((await realpath(path)) !== path || !(await lstat(path)).isFile())
    throw Error("Canonical semantic source must be an owned regular file");
  const bytes = await readFile(path);
  if (bytes.length > 262144 || !bytes.toString("utf8").startsWith("/**"))
    throw Error("Bounded canonical TypeScript semantic source required");
  const sourceSha256 = createHash("sha256").update(bytes).digest("hex");
  const header =
    "// Generated by agent-platform/scripts/generate-hermes-semantic-context.ts. Do not edit this projection.\n" +
    "// canonical-source: " +
    relativeSource +
    "\n" +
    "// canonical-source-sha256: " +
    sourceSha256 +
    "\n" +
    "// Native owner import paths, source readers, data, policy and permissions remain unchanged.\n";
  if (
    createHash("sha256")
      .update(await readFile(path))
      .digest("hex") !== sourceSha256
  )
    throw Error("Canonical semantic source changed during generation");
  return {
    bytes: Buffer.concat([Buffer.from(header), bytes]),
    source: { path: relativeSource, sha256: sourceSha256 },
    authority: "none" as const,
  };
}
if (import.meta.main) {
  if (process.argv.length !== 2)
    throw Error(
      "Usage: bun scripts/generate-hermes-semantic-context.ts > <new-owned-projection.ts>",
    );
  process.stdout.write((await generateHermesSemanticProjection()).bytes);
}
