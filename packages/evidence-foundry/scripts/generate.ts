import { compile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url).pathname;
const source = await readFile(root + "schemas/storage.schema.json", "utf8");
const result = await compile(JSON.parse(source), "StorageRecord", { bannerComment: "/** Generated from schemas/storage.schema.json. Do not edit. */", additionalProperties: false });
await mkdir(root + "src/generated", {recursive:true});
const files = [["src/generated/storage.ts", result], ["src/generated/client.ts", `/** Generated by scripts/generate.ts. Do not edit. */
import type { Foundry, QueryOptions, ActionRequest, ActionResult, CaptureInput } from "../service";
export class EvidenceClient {
  constructor(readonly service: Foundry) {}
  ingestCapture(input: CaptureInput) { return this.service.ingestCapture(input); }
  queryEvidence(options: QueryOptions) { return this.service.queryEvidence(options); }
  queryObjects(options: QueryOptions) { return this.service.queryObjects(options); }
  traverseLinks(id: string, depth = 1) { return this.service.traverseLinks(id, depth); }
  getProvenance(id: string) { return this.service.getProvenance(id); }
  runAction(request: ActionRequest, options?: { simulate?: boolean }): Promise<ActionResult> { return this.service.runAction(request, options); }
  runSuite(id: string, options?: Parameters<Foundry["runSuite"]>[1]) { return this.service.runSuite(id, options); }
  verifyClaim(id: string, options?: Parameters<Foundry["verifyClaim"]>[1]) { return this.service.verifyClaim(id, options); }
}
`]];
for (const [path, content] of files) {
  if (Bun.argv.includes("--check")) { if (await readFile(root + path, "utf8").catch(() => "") !== content) throw new Error("Generated file drift: " + path); }
  else await writeFile(root + path, content!);
}
